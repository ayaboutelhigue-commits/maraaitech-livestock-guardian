// Approximate commune coordinates (offset from wilaya center)
export const COMMUNE_COORDS: Record<string, { lat: number; lng: number }> = {};

// Generate approximate commune coordinates based on wilaya center with small offsets
Object.entries(WILAYA_COMMUNES).forEach(([wilaya, communes]) => {
  const center = WILAYA_COORDS[wilaya];
  if (!center) return;
  communes.forEach((commune, i) => {
    const angle = (2 * Math.PI * i) / communes.length;
    const r = 0.05 + Math.random() * 0.1;
    COMMUNE_COORDS[`${wilaya}|${commune}`] = {
      lat: center.lat + r * Math.sin(angle),
      lng: center.lng + r * Math.cos(angle),
    };
  });
});
